"""Ingest one press-interview submission (a GitHub issue filed from the site's
Press interviews tab). Reads the issue body from a file so nothing in it ever
touches a shell; writes a markdown summary for the issue comment.

    python scripts/press_interview.py --body issue_body.md --issue 12 --summary out.md
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from mpclock.corpus.press_interviews import ingest, parse_submission
from mpclock.schema import load_corpus, save_corpus

CORPUS = ROOT / "data/processed/corpus.jsonl"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--body", required=True)
    ap.add_argument("--issue", type=int, default=None)
    ap.add_argument("--summary", default="press_interview_summary.md")
    ap.add_argument("--no-llm", action="store_true", help="skip classification and coding (testing)")
    args = ap.parse_args()
    sub = parse_submission(Path(args.body).read_text(encoding="utf-8"))
    corpus = load_corpus(CORPUS)
    n0 = len(corpus)
    entry, corpus = ingest(sub, corpus, args.issue, classify=not args.no_llm, code=not args.no_llm)
    if entry["status"] in ("added", "duplicate") and (len(corpus) != n0 or entry.get("replaced_text")):
        save_corpus(corpus, CORPUS)
    sig = entry.get("signal")
    lines = [f"**{entry['status'].replace('_', ' ')}** — {entry['reason']}", "",
             f"- member: {entry.get('member')}", f"- date: {entry.get('date')}",
             f"- outlet: {entry.get('outlet') or '—'}", f"- links: {', '.join(entry.get('urls') or []) or '—'}"]
    if entry.get("words"):
        lines.append(f"- text: {entry['words']} words ({entry.get('text_source')})")
    if sig:
        p = sig["p"]
        lines.append("- signalled next vote: " + ", ".join(f"{k.replace('_', ' ')} {v:.0%}" for k, v in p.items()))
    for e in entry.get("fetch_errors", []):
        lines.append(f"- could not fetch {e}")
    lines += ["", "---", "_Generated by [Claude Code](https://claude.ai/code)_"]
    Path(args.summary).write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
